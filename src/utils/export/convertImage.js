import { splitPlan } from "@/utils/model/evaluation";
import { IMAGE_SIZE } from "@/utils/image/imageDataset";
import { JS_OPTIMIZERS, PY_OPTIMIZERS } from "@/utils/export/convert";

const FILTERS = [16, 32, 64];
const DENSE_UNITS = 64;
const DROPOUT = 0.3;
const PATIENCE = 10; // same as EARLY_STOPPING_PATIENCE in training.js
const SEED = 42;

const q = JSON.stringify;
const indent = (lines, pad = "    ") => lines.map((l) => (l ? pad + l : l));

const PY_SET = { train: "tr", validation: "val", test: "te" };
const NODE_SET = { train: "Train", validation: "Val", test: "Test" };

function resolve({ config, dataset, meta }) {
    if (!PY_OPTIMIZERS[config.optimizer]) {
        throw new Error(`Unknown optimizer: ${config.optimizer}.`);
    }

    const classes = meta?.classes;
    if (!Array.isArray(classes) || classes.length < 2) {
        throw new Error("The class names are needed to generate the code.");
    }

    const rowCount = Array.isArray(dataset.rows) ? dataset.rows.length : Number(dataset.rows) || 0;
    const plan = splitPlan(rowCount);
    const validationSplit = meta?.validationSplit ?? plan.validation;
    const testSplit = meta?.testSplit ?? plan.test;

    return {
        folder: dataset.fileName || "images",
        classes,
        validationSplit,
        testSplit,
        earlyStopping: Boolean(config.earlyStopping) && validationSplit > 0,
        evalSet: testSplit > 0 ? "test" : validationSplit > 0 ? "validation" : "train",
    };
}

export function generateImagePythonCode(run) {
    const { config } = run;
    const r = resolve(run);
    const val = r.validationSplit;
    const test = r.testSplit;
    const s = PY_SET[r.evalSet];

    const L = [
        "# Generated by Neural Network Playground (image training)",
        "# pip install tensorflow pillow numpy",
        "import json",
        "import os",
        "import numpy as np",
        "from PIL import Image",
        "from tensorflow import keras",
        "from tensorflow.keras import layers",
        "",
        `SEED = ${SEED}`,
        "keras.utils.set_random_seed(SEED)",
        "",
        "# 1. Folder and classes (one subfolder per class, images inside each subfolder)",
        `DATA_DIR = ${q(r.folder)}`,
        `classes = ${q(r.classes)}`,
        "",
        `# 2. Read images: resized to ${IMAGE_SIZE}x${IMAGE_SIZE}, RGB values scaled to 0-1`,
        "# Transparent pixels become white, the same as on the training page.",
        "images = []",
        "labels = []",
        "for class_index, class_name in enumerate(classes):",
        "    class_dir = os.path.join(DATA_DIR, class_name)",
        "    for file_name in sorted(os.listdir(class_dir)):",
        '        if not file_name.lower().endswith((".jpg", ".jpeg", ".png", ".webp", ".bmp", ".gif")):',
        "            continue",
        "        with Image.open(os.path.join(class_dir, file_name)) as img:",
        '            rgba = img.convert("RGBA")',
        '            canvas = Image.new("RGBA", rgba.size, (255, 255, 255, 255))',
        "            canvas.alpha_composite(rgba)",
        `            rgb = canvas.convert("RGB").resize((${IMAGE_SIZE}, ${IMAGE_SIZE}), Image.BILINEAR)`,
        '        images.append(np.asarray(rgb, dtype="float32") / 255.0)',
        "        labels.append(class_index)",
        "",
        "X = np.stack(images)",
        `y = keras.utils.to_categorical(np.array(labels), ${r.classes.length})`,
        "",
        "# 3. Shuffle and split the data",
        "order = np.random.default_rng(SEED).permutation(len(X))",
        "X, y = X[order], y[order]",
        `n_val = ${val > 0 ? `max(1, int(len(X) * ${val} + 0.5))` : 0}`,
        `n_test = ${test > 0 ? `max(1, int(len(X) * ${test} + 0.5))` : 0}`,
        "n_train = len(X) - n_val - n_test",
        "X_tr, y_tr = X[:n_train], y[:n_train]",
    ];
    if (val > 0) L.push("X_val, y_val = X[n_train:n_train + n_val], y[n_train:n_train + n_val]");
    if (test > 0) L.push("X_te, y_te = X[n_train + n_val:], y[n_train + n_val:]");

    L.push(
        "",
        "# 4. Model: three convolution + pooling blocks, then dense layers",
        "model = keras.Sequential([",
        `    layers.Input(shape=(${IMAGE_SIZE}, ${IMAGE_SIZE}, 3)),`,
        ...FILTERS.flatMap((f) => [
            `    layers.Conv2D(${f}, 3, padding="same", activation="relu"),`,
            "    layers.MaxPooling2D(2),",
        ]),
        "    layers.Flatten(),",
        `    layers.Dropout(${DROPOUT}),`,
        `    layers.Dense(${DENSE_UNITS}, activation="relu"),`,
        `    layers.Dense(${r.classes.length}, activation="softmax"),`,
        "])",
        "model.compile(",
        `    optimizer=${PY_OPTIMIZERS[config.optimizer](config.learningRate)},`,
        '    loss="categorical_crossentropy",',
        '    metrics=["accuracy"],',
        ")",
        "",
        "# 5. Training",
        "model.fit(",
        `    X_tr, y_tr, epochs=${config.epochs}, batch_size=${config.batchSize},`,
        ...(val > 0 ? ["    validation_data=(X_val, y_val),"] : []),
        ...(r.earlyStopping
            ? [`    callbacks=[keras.callbacks.EarlyStopping(monitor="val_loss", patience=${PATIENCE})],`]
            : []),
        "    shuffle=True,",
        "    verbose=2,",
        ")",
        "",
        `# Evaluate on the ${r.evalSet} data`,
        `pred = model.predict(X_${s}, verbose=0).argmax(axis=1)`,
        `actual = y_${s}.argmax(axis=1)`,
        `print(f"${r.evalSet} accuracy={(pred == actual).mean():.4f}")`,
        "",
        "# 6. Export",
        'model.save("image_model.keras")',
        "# classes.json is needed to turn the model output back into class names",
        'with open("classes.json", "w", encoding="utf-8") as f:',
        `    json.dump({"classes": classes, "image_size": ${IMAGE_SIZE}}, f, indent=2, ensure_ascii=False)`,
        ""
    );

    return L.join("\n");
}

export function generateImageNodeCode(run) {
    const { config } = run;
    const r = resolve(run);
    const val = r.validationSplit;
    const test = r.testSplit;
    const s = NODE_SET[r.evalSet];

    const body = [
        "// 1. Folder and classes (one subfolder per class, images inside each subfolder)",
        `const DATA_DIR = ${q(r.folder)};`,
        `const classes = ${q(r.classes)};`,
        "",
        `// 2. Read images: resized to ${IMAGE_SIZE}x${IMAGE_SIZE}, RGB values scaled to 0-1`,
        "// tfjs-node reads JPG, PNG, BMP and GIF. Other files (such as WebP) are skipped.",
        "const imageTensors = [];",
        "const labels = [];",
        "for (const [classIndex, className] of classes.entries()) {",
        "    const classDir = path.join(DATA_DIR, className);",
        "    for (const fileName of fs.readdirSync(classDir)) {",
        "        const extension = path.extname(fileName).toLowerCase();",
        '        if (![".jpg", ".jpeg", ".png", ".bmp", ".gif"].includes(extension)) continue;',
        "",
        '        const decoded = tf.node.decodeImage(fs.readFileSync(path.join(classDir, fileName)), 3, "int32", false);',
        `        const resized = tf.image.resizeBilinear(tf.cast(decoded, "float32"), [${IMAGE_SIZE}, ${IMAGE_SIZE}]).div(255);`,
        "        decoded.dispose();",
        "        imageTensors.push(resized);",
        "        labels.push(classIndex);",
        "    }",
        "}",
        "",
        "// 3. Shuffle and split the data",
        "const n = imageTensors.length;",
        "const order = Array.from(tf.util.createShuffledIndices(n));",
        "const xs = tf.stack(order.map((i) => imageTensors[i]));",
        `const ys = tf.oneHot(tf.tensor1d(order.map((i) => labels[i]), "int32"), ${r.classes.length}).toFloat();`,
        "imageTensors.forEach((tensor) => tensor.dispose());",
        "",
        `const nVal = ${val > 0 ? `Math.max(1, Math.round(n * ${val}))` : 0};`,
        `const nTest = ${test > 0 ? `Math.max(1, Math.round(n * ${test}))` : 0};`,
        "const nTrain = n - nVal - nTest;",
        "const xTrain = xs.slice([0, 0, 0, 0], [nTrain, -1, -1, -1]);",
        "const yTrain = ys.slice([0, 0], [nTrain, -1]);",
        ...(val > 0
            ? [
                  "const xVal = xs.slice([nTrain, 0, 0, 0], [nVal, -1, -1, -1]);",
                  "const yVal = ys.slice([nTrain, 0], [nVal, -1]);",
              ]
            : []),
        ...(test > 0
            ? [
                  `const xTest = xs.slice([${val > 0 ? "nTrain + nVal" : "nTrain"}, 0, 0, 0], [nTest, -1, -1, -1]);`,
                  `const yTest = ys.slice([${val > 0 ? "nTrain + nVal" : "nTrain"}, 0], [nTest, -1]);`,
              ]
            : []),
        "",
        "// 4. Model: three convolution + pooling blocks, then dense layers",
        "const model = tf.sequential();",
        ...FILTERS.flatMap((f, i) => [
            `model.add(tf.layers.conv2d({ filters: ${f}, kernelSize: 3, padding: "same", activation: "relu"${
                i === 0 ? `, inputShape: [${IMAGE_SIZE}, ${IMAGE_SIZE}, 3]` : ""
            } }));`,
            "model.add(tf.layers.maxPooling2d({ poolSize: 2 }));",
        ]),
        "model.add(tf.layers.flatten());",
        `model.add(tf.layers.dropout({ rate: ${DROPOUT} }));`,
        `model.add(tf.layers.dense({ units: ${DENSE_UNITS}, activation: "relu" }));`,
        `model.add(tf.layers.dense({ units: ${r.classes.length}, activation: "softmax" }));`,
        "model.compile({",
        `    optimizer: ${JS_OPTIMIZERS[config.optimizer](config.learningRate)},`,
        '    loss: "categoricalCrossentropy",',
        '    metrics: ["accuracy"],',
        "});",
        "",
        "// 5. Training",
        "await model.fit(xTrain, yTrain, {",
        `    epochs: ${config.epochs},`,
        `    batchSize: ${config.batchSize},`,
        ...(val > 0 ? ["    validationData: [xVal, yVal],"] : []),
        ...(r.earlyStopping
            ? [`    callbacks: [tf.callbacks.earlyStopping({ monitor: "val_loss", patience: ${PATIENCE} })],`]
            : []),
        "    shuffle: true,",
        "    verbose: 1,",
        "});",
        "",
        `// Evaluate on the ${r.evalSet} data`,
        `const predicted = model.predict(x${s}).argMax(-1).dataSync();`,
        `const actual = y${s}.argMax(-1).dataSync();`,
        "let correct = 0;",
        "for (let i = 0; i < actual.length; i++) {",
        "    if (predicted[i] === actual[i]) correct++;",
        "}",
        `console.log("${r.evalSet} accuracy", (correct / actual.length).toFixed(4));`,
        "",
        "// 6. Export",
        'await model.save("file://./image-model-output");',
        "// classes.json is needed to turn the model output back into class names",
        "fs.writeFileSync(",
        '    "./image-model-output/classes.json",',
        `    JSON.stringify({ classes, imageSize: ${IMAGE_SIZE} }, null, 2)`,
        ");",
    ];

    return [
        "// Generated by Neural Network Playground (image training)",
        "// npm install @tensorflow/tfjs-node",
        'const fs = require("fs");',
        'const path = require("path");',
        'const tf = require("@tensorflow/tfjs-node");',
        "",
        "async function main() {",
        ...indent(body),
        "}",
        "",
        "main().catch((err) => {",
        "    console.error(err.message);",
        "    process.exit(1);",
        "});",
        "",
    ].join("\n");
}

export const IMAGE_GENERATORS = {
    python: generateImagePythonCode,
    node: generateImageNodeCode,
};